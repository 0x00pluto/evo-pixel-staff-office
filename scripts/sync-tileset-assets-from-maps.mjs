#!/usr/bin/env node
/**
 * Sync Phaser tileset preload list from packed map JSON.
 *
 * Source of truth: tilesets[] on maps listed in registry.json.
 * Writes:
 *   - public/assets/maps/registry.json  (tilesets field)
 *   - src/game/tilesetAssets.generated.ts
 *
 *   pnpm sync:tileset-assets
 *   (also run by gen:assets after pack:tilesets)
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const root = path.join(__dirname, '..')
const mapsDir = path.join(root, 'public', 'assets', 'maps')
const registryPath = path.join(mapsDir, 'registry.json')
const outTs = path.join(root, 'src', 'game', 'tilesetAssets.generated.ts')

function fail(msg) {
  console.error(`FAIL: ${msg}`)
  process.exit(1)
}

function mapJsonPathFromUrl(jsonUrl) {
  // "/assets/maps/company-25.json" → public/assets/maps/company-25.json
  const rel = String(jsonUrl || '').replace(/^\/assets\//, '')
  if (!rel || rel.includes('..')) fail(`bad map json url: ${jsonUrl}`)
  return path.join(root, 'public', 'assets', rel)
}

function entryFromTileset(t) {
  const name = t.name
  if (!name) fail('tileset missing name')
  const image = String(t.image || '').replace(/\\/g, '/')
  if (!image) fail(`tileset «${name}» has no image — run pnpm pack:tilesets`)
  if (t.source) {
    fail(
      `tileset «${name}» still has source «${t.source}» — run pnpm pack:tilesets before sync`,
    )
  }
  const url = `/assets/maps/${image}`
  const key = image.includes('/village/') ? `ts_village_${name}` : `ts_${name}`
  return { name, key, url }
}

function main() {
  if (!fs.existsSync(registryPath)) fail(`missing ${registryPath}`)
  const registry = JSON.parse(fs.readFileSync(registryPath, 'utf8'))
  const maps = registry.maps
  if (!maps || typeof maps !== 'object') fail('registry.json missing maps')

  const byName = new Map()
  const order = []

  for (const id of Object.keys(maps)) {
    const entry = maps[id]
    const mapPath = mapJsonPathFromUrl(entry.json)
    if (!fs.existsSync(mapPath)) fail(`map file missing for ${id}: ${mapPath}`)
    const map = JSON.parse(fs.readFileSync(mapPath, 'utf8'))
    for (const t of map.tilesets || []) {
      if (t.source && !t.image) {
        fail(
          `${id}: tileset «${t.name || '?'}» still has source — run pnpm pack:tilesets`,
        )
      }
      if (!t.image) continue
      const item = entryFromTileset(t)
      if (byName.has(item.name)) {
        const prev = byName.get(item.name)
        if (prev.url !== item.url || prev.key !== item.key) {
          fail(
            `tileset name «${item.name}» conflict: ${prev.url} vs ${item.url}`,
          )
        }
        continue
      }
      byName.set(item.name, item)
      order.push(item.name)
    }
  }

  const tilesets = order.map((n) => byName.get(n))
  registry.tilesets = tilesets
  fs.writeFileSync(registryPath, `${JSON.stringify(registry, null, 2)}\n`)

  const lines = [
    '/* eslint-disable */',
    '// AUTO-GENERATED by scripts/sync-tileset-assets-from-maps.mjs — do not edit.',
    '// Source: tilesets[] on maps in public/assets/maps/registry.json',
    "import type { TilesetEntry } from './mapRegistry'",
    '',
    'export const TILESET_ASSETS: TilesetEntry[] = [',
  ]
  for (const t of tilesets) {
    lines.push('  {')
    lines.push(`    name: ${JSON.stringify(t.name)},`)
    lines.push(`    key: ${JSON.stringify(t.key)},`)
    lines.push(`    url: ${JSON.stringify(t.url)},`)
    lines.push('  },')
  }
  lines.push(']', '')
  fs.mkdirSync(path.dirname(outTs), { recursive: true })
  fs.writeFileSync(outTs, lines.join('\n'))

  console.log(
    `sync:tileset-assets → ${tilesets.length} tilesets (registry.json + tilesetAssets.generated.ts)`,
  )
  const artish = tilesets.filter(
    (t) => !String(t.url).includes('/village/') && !/tileset\d|Special_Zones/.test(t.name),
  )
  if (artish.length) {
    console.log(`  art/custom: ${artish.map((t) => t.name).join(', ')}`)
  }
}

main()
